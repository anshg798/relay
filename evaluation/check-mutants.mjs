#!/usr/bin/env node
// npm run check:mutants [-- --only M01-...,M02-...] [--regen] [--concurrency N]
// Applies every mutant patch to a copy of reference/, builds it, runs the full
// verifier and requires that at least one score-bearing check fails.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { parseArgs } from "node:util";
import { evaluate, ROOT } from "./lib/evaluate.mjs";
import { mutants } from "./mutants/mutants.mjs";

const { values } = parseArgs({
  options: {
    only: { type: "string" },
    regen: { type: "boolean", default: false },
    concurrency: { type: "string", default: "4" },
  },
});

const REF = path.join(ROOT, "reference");
const MUT_DIR = path.join(ROOT, "evaluation", "mutants");
const POW = path.join(ROOT, "evaluation", "proof-of-work", "mutants");

function copyReference(dest) {
  fs.cpSync(REF, dest, {
    recursive: true,
    filter: (src) => !path.relative(REF, src).split(path.sep).some((p) => ["node_modules", "dist", "data"].includes(p)),
  });
}

function regenerate() {
  for (const m of mutants) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "relay-mut-gen-"));
    const original = fs.readFileSync(path.join(REF, m.file), "utf8");
    let mutated = original;
    for (const [find, replace] of m.edits) {
      const count = mutated.split(find).length - 1;
      if (count !== 1) throw new Error(`${m.id}: expected exactly one match, found ${count}: ${find.slice(0, 60)}`);
      mutated = mutated.replace(find, () => replace);
    }
    fs.writeFileSync(path.join(tmp, "a"), original);
    fs.writeFileSync(path.join(tmp, "b"), mutated);
    const d = spawnSync("diff", ["-u", "--label", `a/${m.file}`, "--label", `b/${m.file}`, path.join(tmp, "a"), path.join(tmp, "b")], {
      encoding: "utf8",
    });
    if (d.status !== 1) throw new Error(`${m.id}: diff produced no change`);
    fs.writeFileSync(path.join(MUT_DIR, `${m.id}.patch`), `# ${m.id}: ${m.description}\n${d.stdout}`);
    fs.rmSync(tmp, { recursive: true, force: true });
  }
  console.log(`regenerated ${mutants.length} patches in ${path.relative(ROOT, MUT_DIR)}`);
}

if (values.regen) {
  regenerate();
  process.exit(0);
}

const selected = values.only ? mutants.filter((m) => values.only.split(",").includes(m.id)) : mutants;
fs.mkdirSync(POW, { recursive: true });
const rows = [];
let survivors = 0;

for (const m of selected) {
  const patchFile = path.join(MUT_DIR, `${m.id}.patch`);
  if (!fs.existsSync(patchFile)) throw new Error(`missing ${patchFile}; run with --regen`);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `relay-${m.id}-`));
  copyReference(dir);
  const p = spawnSync("patch", ["-p1", "--quiet", "-i", patchFile], { cwd: dir, encoding: "utf8" });
  if (p.status !== 0) throw new Error(`${m.id}: patch failed\n${p.stdout}${p.stderr}`);

  const result = await evaluate({
    solutionDir: dir,
    label: m.id,
    out: path.join(POW, `${m.id}.json`),
    concurrency: Number(values.concurrency),
  });
  const failed = result.checks.filter((c) => !c.passed).map((c) => c.id);
  const killed = result.built && failed.length > 0;
  if (!killed) survivors++;
  rows.push({ id: m.id, description: m.description, killed, score: result.scorePercent, failed, built: result.built });
  console.log(`${killed ? "KILLED  " : "SURVIVED"} ${m.id.padEnd(34)} score ${String(result.scorePercent).padStart(6)}%  failing: ${failed.join(", ") || "-"}`);
  fs.rmSync(dir, { recursive: true, force: true });
}

if (!values.only) {
  const md = [
    "# Mutant report",
    "",
    "Generated by `npm run check:mutants`. A mutant is **killed** when it builds and at least one",
    "score-bearing verifier check fails against it.",
    "",
    `Killed: **${rows.length - survivors}/${rows.length}**`,
    "",
    "| Mutant | Bug | Killed | Score | Failing checks |",
    "|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.id} | ${r.description} | ${r.killed ? "yes" : "**NO**"} | ${r.score}% | ${r.failed.join(", ")} |`),
    "",
  ].join("\n");
  fs.writeFileSync(path.join(POW, "README.md"), md);
  fs.writeFileSync(path.join(POW, "summary.json"), JSON.stringify(rows, null, 2) + "\n");
}

console.log(`\n${rows.length - survivors}/${rows.length} mutants killed`);
process.exit(survivors === 0 ? 0 : 1);
